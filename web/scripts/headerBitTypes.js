export const verifyNibble = (str) => {
    return /^[0-9A-F]]+$/.test(str);
}
export const verifyNibbit = (str) => {
    return /^[A-Z@.:/-]+$/.test(str);
}
export const verifyNibblit = (str) => {
    return /^[0-9A-Za-z@.\s]+$/.test(str);
}
